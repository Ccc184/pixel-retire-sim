/**
 * 根据玩家初始选择，生成一句简短的"回响"——不是硬拼接的段落，
 * 而是结尾处的一句轻声感叹，像多年后回头看自己当年的选择。
 */
function getEcho(choices: OriginChoices): string {
  const cityEchoes = [
    '那年义无反顾踏上的列车，终究带你到了一个你不曾预想的站台。',
    '你并非为野心而来，却在这座城市里长出了自己的根。',
    '你循着一个人来，最后发现能让自己站稳的，从来不是别人的脚步。',
  ];
  const careerEchoes = [
    '你算计着、忍耐着，每一步都算数。',
    '你死死抱住的那根浮木，最终真的托住了你。',
    '饿着肚子也要把灵魂喂饱的人，往往真的能找到饭吃。',
  ];
  const riskEchoes = [
    '你从未在牌桌下蜷缩过，这就够了。',
    '你走在不偏不倚的窄路上，身后是刚刚好的月光。',
    '活着本身需要最多的勇气，你做到了。',
  ];
  // 三选一，简洁收尾
  const seed = (choices.cityReason * 7 + choices.careerMotivation * 13 + choices.riskAttitude * 3) % 3;
  const echoes = [cityEchoes[choices.cityReason], careerEchoes[choices.careerMotivation], riskEchoes[choices.riskAttitude]];
  return echoes[seed];
}

